package _training;


public class Dominic {
    public static void main(String[] args) {
        int num = 1;
        int num2 = 2;
        int num3 = num + num;
        int num4 = num3 + num2;
        int num5 = num4 + num3;
        int num6 = num5 + num4;
        System.out.println(num6);
        int num7 = num - num;
        int num8 = num3 - num7;
        int num9 = num4 - num8;
        int num10 = num5 - num9;
        System.out.println(num10);
        int num11 = num / num;
        int num12 = num3 / num11;
        int num13 = num4 / num12;
        int num14 = num5 / num13;
        System.out.println(num14);
        
    }
    
}
