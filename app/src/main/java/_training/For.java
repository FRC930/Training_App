package _training;

public class For {
    public static void main(String[] args) {
        for (int i = 0; i > 20; i++) {
            for (int quarters = 0; quarters > 5; quarters++){
            System.out.println("i ran in " + quarters + " quarters of the " + i + " circle!");
            }
            System.out.println("I ran in " + i + " circles today!");
        }
    }
}
