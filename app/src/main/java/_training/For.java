package _training;

public class For {
    public static void main(String[] args) {
        for (int i = 0; i < 40; i++) {
            for (int q = 1; q < 5; q++) {
                System.out.println("I ran in " + q + " Quarters of a circle so far!");
            }
            System.out.println("I ran in " + i + " circles today!");
        }
    }
}
